def _run_script(sql: str) -> None:
    """Run a multi-statement script inside Alembic's transaction.

    asyncpg prepares single statements, so a script goes through its simple
    query protocol on the same connection. The SELECT opens the transaction
    first, so the script cannot run outside it.
    """
